// Optional browser check: npm install playwright, then pass a Chromium binary.
const {chromium} = require('playwright');
const {strict: assert} = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {execFileSync} = require('node:child_process');

(async () => {
  const root = path.resolve(__dirname, '..');
  execFileSync(process.env.PYTHON || 'python', [path.join(root, 'tools/report_states.py')]);
  const output = path.join(root, 'artifacts/verification/ui');
  const browser = await chromium.launch({executablePath: process.argv[2], headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage']});
  const page = await browser.newPage({viewport: {width: 1280, height: 900}});
  const errors = [], requests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (/^https?:/.test(r.url())) requests.push(r.url()); });
  await page.goto(pathToFileURL(path.join(output, 'states.html')).href);
  assert.equal(await page.locator('.finding').count(), 3);
  await page.locator('.finding').first().focus();
  await page.keyboard.press('ArrowDown');
  assert.match(await page.locator('#detail').textContent(), /Dependency requires/);
  assert.equal(await page.locator('.finding[aria-pressed="true"]').count(), 1);
  await page.locator('#search').fill('no-such-finding');
  assert.match(await page.locator('#finding-list').textContent(), /No matching findings/);
  await page.getByRole('button', {name: 'Clear filters'}).click();
  assert.equal(await page.locator('.finding').count(), 3);
  await page.locator('#severity').selectOption('error');
  assert.equal(await page.locator('.finding').count(), 1);
  await page.locator('#severity').selectOption('all');
  await page.getByRole('tab', {name: /Inventory/}).click();
  assert.equal(await page.locator('#inventory-panel').isVisible(), true);
  assert.match(await page.locator('#distribution-table').textContent(), /\$SCAN_1/);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.keyboard.press('ArrowLeft');
  assert.equal(await page.locator('#findings-panel').isVisible(), true);
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', {name: 'Download JSON'}).click();
  const download = await downloadEvent;
  const data = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
  assert.equal(data.paths_redacted, true);
  assert.equal(data.findings.length, 3);
  assert.equal(await page.evaluate(() => window.injected), undefined);
  assert.equal(await page.locator('script').count(), 2);
  await page.screenshot({path: path.join(output, 'report-states-1280.png'), fullPage: true});
  await page.setViewportSize({width: 760, height: 900});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({path: path.join(output, 'report-states-760.png'), fullPage: true});
  await page.goto(pathToFileURL(path.join(output, 'empty.html')).href);
  assert.match(await page.locator('#detail').textContent(), /No findings/);
  await page.goto(pathToFileURL(path.join(output, 'demo-report.html')).href);
  await page.setViewportSize({width: 1440, height: 1000});
  await page.screenshot({path: path.join(output, 'report-desktop.png'), fullPage: true});
  assert.deepEqual(errors, []);
  assert.deepEqual(requests, []);
  fs.writeFileSync(path.join(output, 'report-checks.json'), JSON.stringify({status:'passed', browser:await browser.version(), viewports:[1280,760,1440], checks:['selection','keyboard','search recovery','severity','inventory','JSON download','XSS','no document overflow','empty result','no external requests'], synthetic_fixtures:true}, null, 2));
  await browser.close();
  console.log('Report browser checks passed');
})().catch(e => { console.error(e); process.exit(1); });
